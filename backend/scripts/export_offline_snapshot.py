"""
Exports a read-only snapshot of a REAL SentinelGraph run for the frontend's offline mode.

    cd backend && python scripts/export_offline_snapshot.py

Seeds a fresh temporary database exactly as the server does on first start, calls the real API
and writes frontend/src/api/offlineSnapshot.ts. The UI shows an "offline" banner whenever this
snapshot is used, so it is never mistaken for live data.
"""
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.dirname(HERE)
OUT = os.path.join(os.path.dirname(BACKEND), "frontend", "src", "api", "offlineSnapshot.ts")
sys.path.insert(0, BACKEND)

tmp = os.path.join(tempfile.mkdtemp(), "snapshot.db")
os.environ["DATABASE_URL"] = f"sqlite:///{tmp}"
os.environ["SEED_IN_BACKGROUND"] = "false"

from fastapi.testclient import TestClient  # noqa: E402
from app.main import app  # noqa: E402

with TestClient(app) as client:  # startup runs migrations + the same auto-seed as production
    get = lambda path, **params: client.get(f"/api{path}", params=params).json()
    cases = get("/investigations", limit=50)
    snapshot = {
        "generatedFrom": "A real run of SentinelGraph (scripts/export_offline_snapshot.py)",
        "health": {**get("/health"), "llm_mode": "offline_snapshot"},
        "stats": get("/alerts/stats/summary"),
        "alerts": get("/alerts", limit=60),
        "cases": cases,
        "caseDetails": {c["case_id"]: get(f"/investigations/{c['case_id']}") for c in cases},
        "auditLogs": get("/audit", limit=200),
        "evaluation": get("/evaluation/latest"),
    }

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// AUTO-GENERATED by backend/scripts/export_offline_snapshot.py — do not edit by hand.\n")
    fh.write("// Read-only data from a real run, shown only when the API is unreachable (with a banner).\n")
    fh.write("export const OFFLINE_SNAPSHOT: Record<string, any> = ")
    json.dump(snapshot, fh, indent=1, default=str)
    fh.write(";\n")
print(f"Wrote {OUT} ({os.path.getsize(OUT) // 1024} KB, {len(cases)} cases)")
